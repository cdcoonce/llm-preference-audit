"""Write results/profile.json and docs/data-profile.md (aggregates only, no text)."""

import json
from pathlib import Path

from llm_preference_audit.data import load_train
from llm_preference_audit.profile import build_profile, compare_copies
from llm_preference_audit.split import build_manifest

HF = Path("data/raw/train.csv")
KAGGLE = Path("data/kaggle/train.csv")
JSON_OUT = Path("results/profile.json")
MD_OUT = Path("docs/data-profile.md")


def pct(x: float) -> str:
    return f"{100 * x:.2f}%"


def render(p: dict) -> str:
    lab, pos, ln = p["labels"], p["labels"]["position"], p["length"]
    v, d, w = p["verbosity_longer_wins"], p["duplicates"], p["length"]["words"]
    cmp = p["hf_vs_kaggle"]
    rep = d["repeat_same_model_pair"]
    lines = [
        "# Data profile",
        "",
        "Generated by `make profile`. Aggregates only; no prompt or response text.",
        "",
        "## Integrity",
        "",
        f"- Rows: {p['rows']}",
        f"- JSON parse failures (prompt / response_a / response_b): {p['integrity']['parse_failures']}",
        f"- Rows with null turns: {p['integrity']['rows_with_null_turns']}",
        f"- One-hot violations: {p['integrity']['onehot_violations']}",
        f"- HF vs Kaggle: {json.dumps(cmp)}",
        "",
        "## Labels and position",
        "",
        "| label | count | share |",
        "|---|---|---|",
        *[f"| {k} | {lab['counts'][k]} | {pct(lab['shares'][k])} |" for k in ("a", "b", "tie")],
        "",
        f"- Class-prior log loss (constant baseline, natural log): {lab['class_prior_log_loss']:.4f}",
        (
            f"- Among {pos['n_nonties']} non-ties: P(a wins) = {pct(pos['p_a_among_nonties'])}, "
            f"P(b wins) = {pct(pos['p_b_among_nonties'])}; 95% Wilson CI for P(a) "
            f"[{pct(pos['p_a_ci95'][0])}, {pct(pos['p_a_ci95'][1])}]"
        ),
        "",
        "## Turns",
        "",
        f"- Multi-turn share: {pct(p['turns']['multi_turn_share'])}",
        f"- Turn-count distribution: {p['turns']['turn_count_distribution']}",
        "",
        "## Length and API sizing",
        "",
        "| words | p50 | p90 | p99 | max |",
        "|---|---|---|---|---|",
        *[
            f"| {k} | {x['p50']:.0f} | {x['p90']:.0f} | {x['p99']:.0f} | {x['max']:.0f} |"
            for k, x in w.items()
        ],
        "",
        (
            f"- Estimated tokens (words x {ln['est_tokens']['tokens_per_word_assumed']}): "
            f"total {ln['est_tokens']['total']:,.0f}, mean per row "
            f"{ln['est_tokens']['per_row_mean']:,.0f}; per row p50/p90/p99 = "
            f"{ln['est_tokens']['per_row']['p50']:.0f} / {ln['est_tokens']['per_row']['p90']:.0f} / "
            f"{ln['est_tokens']['per_row']['p99']:.0f}"
        ),
        "- Share of rows with prompt + both responses over: "
        + ", ".join(
            f"{int(k) // 1000}k tokens {pct(x)}" for k, x in ln["share_over_est_tokens"].items()
        ),
        "",
        "## Preliminary verbosity signal",
        "",
        (
            f"- Among {v['n']} non-ties with unequal word counts the longer response won "
            f"{pct(v['share'])} (95% Wilson CI [{pct(v['ci95'][0])}, {pct(v['ci95'][1])}]). "
            "Unadjusted for quality; a prior, not a finding."
        ),
        "",
        "## Models",
        "",
        f"- Distinct models: {p['models']['n_distinct']}",
        *[f"- {m['model']}: {m['appearances']}" for m in p["models"]["top10"]],
        "",
        "## Duplicates and repeats",
        "",
        f"- Exact duplicate rows: {d['exact_duplicate_rows']}",
        (
            f"- Distinct prompt groups: {d['distinct_prompt_groups']}; groups of size >= 2: "
            f"{d['groups_ge2']} covering {d['rows_in_groups_ge2']} rows"
        ),
        f"- Repeats with the same unordered model pair (all rows): {rep['all_rows']}",
        f"- Same, exact duplicates removed: {rep['exact_duplicates_removed']}",
        f"- Noise ceiling: {d['noise_ceiling']}",
        "",
        "## Splits",
        "",
        "| cell | rows | groups | a | b | tie |",
        "|---|---|---|---|---|---|",
        *[
            f"| {c} | {s['rows']} | {s['groups']} | {pct(s['label_shares']['a'])} | "
            f"{pct(s['label_shares']['b'])} | {pct(s['label_shares']['tie'])} |"
            for c, s in p["splits"].items()
        ],
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    df = load_train(HF)
    comparison = compare_copies(df, load_train(KAGGLE)) if KAGGLE.exists() else None
    profile = build_profile(df, build_manifest(df), comparison)
    JSON_OUT.parent.mkdir(exist_ok=True)
    JSON_OUT.write_text(json.dumps(profile, indent=2) + "\n")
    MD_OUT.parent.mkdir(exist_ok=True)
    MD_OUT.write_text(render(profile))
    print(f"wrote {JSON_OUT} and {MD_OUT}")


if __name__ == "__main__":
    main()
