"""Render the rung-2 LightGBM submission kernel: ONE self-contained script, no attached dataset.

The script inlines the repo modules it needs (read from a pinned clean commit), so the code that
runs on Kaggle is exactly the committed code. Internet off, CPU only. This tool only renders and
prints the push / submit commands; it never pushes or submits.

  uv run python kaggle/lgbm_submission/build_kernel.py              # preflight + render
  uv run python kaggle/lgbm_submission/build_kernel.py --dev --out DIR   # skip preflight (dry run)

The number of boosting rounds is round(mean(best_iterations of the ledger's `full` LightGBM row)
x 1.1), computed here and baked into the script (no early-stopping holdout in the final fit).
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[1]
DEFAULT_OUT = Path("data/kaggle_build/lgbm-sub")
LEDGER = Path("results/ledger.jsonl")
COMPETITION = "llm-classification-finetuning"
SLUG = "charlescoonce/llm-pref-lgbm-sub"
CODE_FILE = "lgbm_submission.py"
ROUND_FACTOR = 1.1
PACKAGE = "llm_preference_audit"
# Dependency order: each module only imports modules listed before it.
MODULES = (
    "data",
    "split",
    "kernel_common",
    "profile",
    "truncate",
    "cv_common",
    "deberta_inputs",
    "features",
    "submission",
    "train_lgbm",
)
THIRD_PARTY = {"numpy", "pandas", "lightgbm"}  # all in the Kaggle image


def _load_rung5_push():
    spec = importlib.util.spec_from_file_location(
        "rung5_push", REPO_ROOT / "kaggle/rung5_deberta/push.py"
    )
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def rounds_from_ledger(path: Path = LEDGER, factor: float = ROUND_FACTOR) -> int:
    """round(mean best_iterations x factor) of the latest `full` LightGBM row."""
    rows = [json.loads(line) for line in Path(path).read_text().splitlines() if line.strip()]
    full = [r for r in rows if r.get("model") == "lightgbm" and r.get("config") == "full"]
    if not full:
        raise SystemExit(f"no lightgbm `full` row in {path}")
    best = full[-1].get("best_iterations")
    if not best:
        raise SystemExit("the latest lightgbm `full` ledger row has no best_iterations")
    return round(sum(best.values()) / len(best) * factor)


def read_source(module: str, sha: str | None) -> str:
    rel = f"{PACKAGE}/{module}.py"
    if sha is None:
        return (REPO_ROOT / rel).read_text()
    return subprocess.run(
        ["git", "show", f"{sha}:{rel}"], check=True, capture_output=True, text=True, cwd=REPO_ROOT
    ).stdout


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def metadata() -> dict:
    return {
        "id": SLUG,
        "title": SLUG.split("/")[1],
        "code_file": CODE_FILE,
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": False,
        "enable_internet": False,
        "competition_sources": [COMPETITION],
        "dataset_sources": [],
        "kernel_sources": [],
        "model_sources": [],
    }


LOADER = """
import hashlib as _hashlib
import sys as _sys
import types as _types

_pkg = _types.ModuleType({package!r})
_pkg.__path__ = []
_sys.modules[{package!r}] = _pkg
for _name, _src in _MODULE_SOURCES.items():  # dependency order
    if _hashlib.sha256(_src.encode("utf-8")).hexdigest() != _BUILD["module_sha256"][_name]:
        raise SystemExit("inlined source of " + _name + " does not match its recorded sha256")
    _mod = _types.ModuleType({package!r} + "." + _name)
    _mod.__package__ = {package!r}
    _mod.__file__ = "<inlined {package}/" + _name + ".py>"
    _sys.modules[_mod.__name__] = _mod
    setattr(_pkg, _name, _mod)
    exec(compile(_src, _mod.__file__, "exec"), _mod.__dict__)
"""


def render_script(sha: str | None, rounds: int, skip_sha_checks: bool = False) -> str:
    sources = {m: read_source(m, sha) for m in MODULES}
    hashes = {m: sha256_text(s) for m, s in sources.items()}
    build = {
        "source_commit": sha or "dev",
        "rounds": rounds,
        "skip_sha_checks": skip_sha_checks,
        "module_sha256": hashes,
        "inlined": True,
    }
    header = [
        "# GENERATED by kaggle/lgbm_submission/build_kernel.py; do not edit.",
        f"# source commit: {build['source_commit']}",
        f"# rounds: {rounds} = round(mean(best_iterations of the ledger `full` row) x {ROUND_FACTOR})",
        "# inlined modules (sha256 of each source):",
        *[f"#   {PACKAGE}/{m}.py  {h}" for m, h in hashes.items()],
        "# third-party imports: numpy, pandas, lightgbm (all in the Kaggle image)",
        "",
        f"_BUILD = {build!r}",
        f"_MODULE_SOURCES = {sources!r}",
        LOADER.format(package=PACKAGE),
    ]
    main_src = (HERE / "kernel_main.py").read_text()
    return "\n".join(header) + "\n" + main_src + "\n\nmain(_BUILD)\n"


def render(out: Path, sha: str | None, rounds: int, skip_sha_checks: bool = False) -> Path:
    out.mkdir(parents=True, exist_ok=True)
    (out / CODE_FILE).write_text(render_script(sha, rounds, skip_sha_checks))
    (out / "kernel-metadata.json").write_text(json.dumps(metadata(), indent=2) + "\n")
    return out


def commands(out: Path) -> list[str]:
    return [
        f"kaggle kernels push -p {out}",
        f"kaggle kernels status {SLUG}",
        f"kaggle kernels output {SLUG} -p data/kaggle_out/lgbm-sub",
        f'kaggle competitions submit -k {SLUG} -v <VERSION> -f submission.csv -m "rung 2 LightGBM full"',
    ]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--dev", action="store_true", help="skip preflight; read the working tree")
    ap.add_argument("--sha", help="commit to pin (must be HEAD); default HEAD")
    a = ap.parse_args(argv)
    rounds = rounds_from_ledger(REPO_ROOT / LEDGER)
    sha = None
    if not a.dev:
        sha = _load_rung5_push().preflight(a.sha)
    out = a.out if a.out.is_absolute() else REPO_ROOT / a.out
    render(out, sha, rounds)
    print(f"rendered {out / CODE_FILE} (rounds {rounds}, commit {sha or 'dev'})")
    print("next (each needs Charles's go; NOT run here):")
    for c in commands(a.out):
        print("  $ " + c)
    return 0


if __name__ == "__main__":
    sys.exit(main())
